import type { Metadata } from 'next';
import { Analytics } from '@vercel/analytics/next';
import { Plus_Jakarta_Sans } from 'next/font/google';
import { Toaster } from './components/ui';
import I18nProvider from './i18n-provider';
import ThemeProvider from './theme-provider';
import './globals.css';

// design-system/CLAUDE.md rule #5: Plus Jakarta Sans only, no second family. Loaded via
// next/font (self-hosted, no runtime request to fonts.googleapis.com) rather than the raw
// @import in design-system/styles.css — same font, this app's own loading convention.
